"""Compare native/WASM search against this build's complete generated index."""
import argparse
import gzip
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import subprocess
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, required=True, help="Built explore directory")
    parser.add_argument("--output", type=Path, required=True, help="New external evidence directory")
    parser.add_argument("--expected-source-head", help="Required for a verified source archive outside Git")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    if (root / '.git').exists():
        source_commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip()
        if args.expected_source_head and args.expected_source_head != source_commit:raise ValueError('Expected source head differs')
        clean = not subprocess.check_output(['git', 'status', '--porcelain', '--untracked-files=no'], cwd=root)
        source_kind = 'git-checkout'
    else:
        if not args.expected_source_head:raise ValueError('Use --expected-source-head outside Git')
        from source_custody import source_data
        from input_custody import strict_json
        source, _ = source_data(root, args.expected_source_head)
        source_commit = strict_json(source['SOURCE-MANIFEST.json'])['source_commit']
        del source
        clean = True
        source_kind = 'verified-complete-source-archive'
    output = Path(os.path.abspath(args.output))
    for parent in [output, *output.parents]:
        if parent.is_symlink() or (parent.exists() and getattr(parent.lstat(), "st_file_attributes", 0) & 0x400):
            raise ValueError("Evidence output must not use a link/junction")
    if output.exists() or output == root or output in root.parents:
        raise ValueError("Use a new evidence directory outside the source root")
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--no-deps", "--format-version", "1"], cwd=root
    ))
    target = Path(metadata["target_directory"]).resolve()
    if target == output or target in output.parents or output in target.parents:
        raise ValueError("Evidence output overlaps the compiled target")
    if root in output.parents:
        raise ValueError("Use an external evidence directory")
    output.mkdir(parents=True)
    compressed = (args.site / "index.json.gz").read_bytes()
    index = output / "index.json"
    index.write_bytes(gzip.decompress(compressed))
    data = json.loads(index.read_bytes())
    def canonical_sha(value):
        return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    fingerprints = dict(
        schema="maxim.index-diagnostics.v1",
        entries=[dict(url=entry["url"], sha256=canonical_sha(entry), text_bytes=len(entry["text"].encode())) for entry in data["entries"]],
        terms_sha256=canonical_sha(data["terms"]),
        scope="Canonical diagnostic fingerprints only; native/WASM parity still compares complete original serialization without normalization.",
    )
    (output / "index-fingerprints.json.gz").write_bytes(gzip.compress(json.dumps(fingerprints, ensure_ascii=False).encode(), mtime=0))
    suffix = ".exe" if os.name == "nt" else ""
    native = target / "debug/examples" / ("search-control" + suffix)
    command = ["node", "tools/check-search.mjs", str(index), str(args.site.resolve() / "pkg"), str(native), str(output / "results")]
    result = subprocess.run(command, cwd=root, capture_output=True)
    (output / "stdout").write_bytes(result.stdout)
    (output / "stderr").write_bytes(result.stderr)
    observation = dict(
        command=command, exit_code=result.returncode,
        source_commit=source_commit, clean_tracked_source=clean, source_kind=source_kind,
        generated_gzip_sha256=hashlib.sha256(compressed).hexdigest(),
        generated_index_sha256=hashlib.sha256(index.read_bytes()).hexdigest(),
        python_version=sys.version,
        python_packages=sorted([dict(name=dist.metadata["Name"], version=dist.version) for dist in importlib.metadata.distributions()], key=lambda row: row["name"].lower()),
        generator_files={name: hashlib.sha256((root / name).read_bytes()).hexdigest() for name in ["requirements.txt", "requirements-build.lock", "tools/build_inputs.py", ".mkdocs/mkdocs.yml", "tools/build-search.py", "tools/build-site.py"]},
        scope="Parity over the complete index generated by this source build; complete source/archive/dependency custody and live deployment remain separate.",
    )
    (output / "build-input.json").write_text(json.dumps(observation, indent=2) + "\n", encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Search parity failed; see {output / 'stderr'}")
    print((output / "results/receipt.json").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
