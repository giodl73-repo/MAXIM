"""Compare native/WASM search against this build's complete generated index."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", type=Path, required=True, help="Built explore directory")
    parser.add_argument("--output", type=Path, required=True, help="New external evidence directory")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    output = Path(os.path.abspath(args.output))
    for parent in [output, *output.parents]:
        if parent.is_symlink() or (parent.exists() and getattr(parent.lstat(), "st_file_attributes", 0) & 0x400):
            raise ValueError("Evidence output must not use a link/junction")
    if output.exists() or output == root or output in root.parents:
        raise ValueError("Use a new evidence directory outside the source root")
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--no-deps", "--format-version", "1"], cwd=root
    ))
    target = Path(metadata["target_directory"]).resolve()
    if target == output or target in output.parents or output in target.parents:
        raise ValueError("Evidence output overlaps the compiled target")
    if root in output.parents:
        raise ValueError("Use an external evidence directory")
    output.mkdir(parents=True)
    compressed = (args.site / "index.json.gz").read_bytes()
    index = output / "index.json"
    index.write_bytes(gzip.decompress(compressed))
    suffix = ".exe" if os.name == "nt" else ""
    native = target / "debug/examples" / ("search-control" + suffix)
    command = ["node", "tools/check-search.mjs", str(index), str(args.site.resolve() / "pkg"), str(native), str(output / "results")]
    result = subprocess.run(command, cwd=root, capture_output=True)
    (output / "stdout").write_bytes(result.stdout)
    (output / "stderr").write_bytes(result.stderr)
    observation = dict(
        command=command, exit_code=result.returncode,
        source_commit=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=root, text=True).strip(),
        clean_tracked_source=not subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], cwd=root),
        generated_gzip_sha256=hashlib.sha256(compressed).hexdigest(),
        generated_index_sha256=hashlib.sha256(index.read_bytes()).hexdigest(),
        scope="Parity over the complete index generated by this source build; complete source/archive/dependency custody and live deployment remain separate.",
    )
    (output / "build-input.json").write_text(json.dumps(observation, indent=2) + "\n", encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Search parity failed; see {output / 'stderr'}")
    print((output / "results/receipt.json").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
